"""Task 1.10: compare the phonemizer's rule tags with an external tajweed annotation dataset.

Reference: tarekeldeeb/quran-tajweed-embedded (README: data file CC BY 4.0; annotations are
generated by rule decision trees, so this is a cross-check, not ground truth).
Its JSON gives rule spans as code point offsets into the Tanzil Uthmani ayah line.

Spans use different conventions (the reference covers noon + space + next letter for an idgham,
we tag the doubled letter), so a rule matches when the spans overlap in the same ayah.

Usage: python3 -I tools/phonemizer/validate.py [REFERENCE.json] [-o docs/VALIDATION_REPORT.md]
"""

