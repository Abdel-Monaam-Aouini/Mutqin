DEFAULT_REF = Path("/tmp/tajweed-ref/output/tajweed.hafs.uthmani-pause-sajdah.json")
DEFAULT_OUT = Path(__file__).resolve().parents[2] / "docs" / "VALIDATION_REPORT.md"

# reference rule -> our rule tags that express it
MAPPING: dict[str, tuple[str, ...]] = {
    "ghunnah": ("ghunnah",),
    "idghaam_ghunnah": ("idgham_ghunnah",),
    "idghaam_no_ghunnah": ("idgham_no_ghunnah",),
    "idghaam_shafawi": ("idgham_mithlayn_saghir",),
    "ikhfa": ("ikhfa",),
    "ikhfa_shafawi": ("ikhfa_shafawi",),
    "iqlab": ("iqlab",),
    "madd_2": ("madd_tabii", "madd_badal", "madd_silah_sughra"),
    "madd_246": ("madd_arid_lissukun", "madd_leen"),
    "madd_muttasil": ("madd_muttasil",),
    "madd_munfasil": ("madd_munfasil", "madd_silah_kubra"),
    "madd_6": ("madd_lazim",),
    "qalqalah": ("qalqalah_sughra", "qalqalah_kubra"),
    "lam_shamsiyyah": ("lam_shamsiyyah",),
    "hamzat_wasl": ("hamzat_wasl",),
}
# Reference spans sit a few characters from where we tag some rules (it marks the lam itself or a
# neighbouring space / vowel, we tag the doubled letter after an assimilated lam): tolerance in
# characters, applied to the reference span.
PAD: dict[str, int] = {"lam_shamsiyyah": 2, "hamzat_wasl": 2, "iqlab": 1}
# A same-rule match within this many characters counts as "near": the rule is found at (almost)
# the same place and only the span differs, which the reference does a few percent of the time.
NEAR = 8
# reference rules with no counterpart in the engine yet
NOT_MODELED = ("silent", "idghaam_mutajanisayn", "idghaam_mutaqaribayn")

Span = tuple[int, int]


def load_reference(path: Path) -> dict[tuple[int, int], list[tuple[str, int, int]]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    return {(e["surah"], e["ayah"]): [(a["rule"], a["start"], a["end"]) for a in e["annotations"]]
            for e in data}


# The reference text is the Tanzil Uthmani text without the waqf signs (U+06D6..U+06DB) and the
# space before each; it keeps tatweel, the basmala prefix and the sajdah sign. Found by testing
# which variant puts ikhfa spans on a noon / tanween (96.5% of 5,301, the rest is noise in the
# reference's own spans).
WAQF_SIGNS = frozenset(chr(c) for c in range(0x06D6, 0x06DC))


def ayah_word_offsets(quran, surah: int, ayah_no: int) -> dict[int, int]:
    """Start offset of each word in the reference text of the ayah."""
    s = quran.surahs[surah - 1]
    ayah = s.ayahs[ayah_no - 1]
    pos = 0
    if ayah_no == 1 and s.basmala:
        pos = sum(len(t) + 1 for t in s.basmala)
    offsets: dict[int, int] = {}
    for w in ayah.words:
        offsets[w.index] = pos
        pos += len(w.text) + 1 + sum(len(m) + 1 for m in w.marks if m not in WAQF_SIGNS)
    return offsets


def ayah_end_reading(quran, result) -> list:
    """The reading the reference describes: continue inside an ayah, stop at every ayah end."""
    stops = {(s.number, a.ayah, len(a.words)) for s in quran.surahs for a in s.ayahs}
    return select_reading(result.items, stops=stops)


def our_annotations(quran, result) -> dict[tuple[int, int], list[tuple[str, int, int, str]]]:
    """{(surah, ayah): [(tag, start, end, word_id)]} in the reference's offset convention."""
    cache: dict[tuple[int, int], dict[int, int]] = {}
    out: dict[tuple[int, int], list[tuple[str, int, int, str]]] = defaultdict(list)
    for item in ayah_end_reading(quran, result):
        key = (item.surah, item.ayah)
        if key not in cache:
            cache[key] = ayah_word_offsets(quran, *key)
        base = cache[key][item.word]
        for tag in item.rules:
            entry = (tag, base + item.span[0], base + item.span[1],
                     f"{item.surah}:{item.ayah}:{item.word}")
            if entry not in out[key]:  # stop / continue copies describe the same location
                out[key].append(entry)
    return out


def overlaps(a_start: int, a_end: int, b_start: int, b_end: int) -> bool:
    return a_start < b_end and b_start < a_end


def compare(ref, ours) -> dict:
    stats: dict[str, Counter] = {r: Counter() for r in MAPPING}
    ref_only: dict[str, list[str]] = defaultdict(list)
    ours_only: dict[str, list[str]] = defaultdict(list)
    tag_to_rule = {t: r for r, tags in MAPPING.items() for t in tags}
    for key in sorted(set(ref) | set(ours)):
        r_list = [x for x in ref.get(key, []) if x[0] in MAPPING]
        o_list = [x for x in ours.get(key, []) if x[0] in tag_to_rule]
        for rule, s, e in r_list:
            tags, pad = MAPPING[rule], PAD.get(rule, 0)
            near = [(os_, oe) for t, os_, oe, _ in o_list if t in tags]
            if any(overlaps(s - pad, e + pad, os_, oe) for os_, oe in near):
                kind = "ref_matched"
            elif any(overlaps(s - NEAR, e + NEAR, os_, oe) for os_, oe in near):
                kind = "ref_near"
            else:
                kind = "ref_only"
                ref_only[rule].append(f"{key[0]}:{key[1]}@{s}-{e}")
            stats[rule]["ref"] += 1
            stats[rule][kind] += 1
        for tag, s, e, wid in o_list:
            rule, pad = tag_to_rule[tag], PAD.get(tag_to_rule[tag], 0)
            same = [(rs, re_) for r, rs, re_ in r_list if r == rule]
            if any(overlaps(rs - pad, re_ + pad, s, e) for rs, re_ in same):
                kind = "ours_matched"
            elif any(overlaps(rs - NEAR, re_ + NEAR, s, e) for rs, re_ in same):
                kind = "ours_near"
            else:
                kind = "ours_only"
                ours_only[rule].append(f"{wid}[{tag}]")
            stats[rule]["ours"] += 1
            stats[rule][kind] += 1
    return {"stats": stats, "ref_only": ref_only, "ours_only": ours_only}


