"""Write docs/SPECIAL_CASES_CANDIDATES.md: locations to confirm with the teacher (ids only).

Usage: python3 -I tools/phonemizer/special_cases_report.py
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tools.phonemizer.phonemize import phonemize_range  # noqa: E402
from tools.phonemizer.special_cases import candidates  # noqa: E402
from tools.quran_text.loader import load_quran  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "docs" / "SPECIAL_CASES_CANDIDATES.md"


def main() -> int:
    quran = load_quran()
    result = phonemize_range([a for s in quran.surahs for a in s.ayahs])
    lines = [
        "# Special-case candidates (generated, unverified)",
        "",
        "Generated by `tools/phonemizer/special_cases_report.py` from the Tanzil text and the engine's",
        "diagnostics. Word ids only. These are places to **confirm with the teacher** before any entry",
        "goes into `tools/phonemizer/data/special_cases.json` (which is still empty).",
        "Spec 3.9 also lists locations that carry no distinguishing sign in the text (sakt at 18:1-2,",
        "36:52, 75:27, 83:14; the two readings at 30:54, 2:245, 7:69, 52:37, 88:22): the teacher gives",
        "the exact words for those.",
        "",
    ]
    for reason, ids in candidates(result).items():
        lines += [f"## {reason} ({len(ids)})", "", ", ".join(ids), ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
